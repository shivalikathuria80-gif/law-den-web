const breakdown = (rating: number, count: number): Record<1 | 2 | 3 | 4 | 5, number> => {
  // Deterministic, plausible distribution for a given average and volume.
  const weights: Record<number, number[]> = {
    5: [0.82, 0.13, 0.03, 0.01, 0.01],
    4: [0.55, 0.28, 0.1, 0.045, 0.025],
    3: [0.3, 0.3, 0.22, 0.11, 0.07],
  };
  const key = rating >= 4.7 ? 5 : rating >= 4.2 ? 4 : 3;
  const w = weights[key];
  const raw = w.map((p) => Math.round(p * count));
  const drift = count - raw.reduce((a, b) => a + b, 0);
  raw[0] += drift;
  return { 5: Math.max(raw[0], 0), 4: raw[1], 3: raw[2], 2: raw[3], 1: raw[4] };
};

